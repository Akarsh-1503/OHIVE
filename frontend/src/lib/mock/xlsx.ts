export function buildXlsx(rows: string[][]): Uint8Array {
  const encoder = new TextEncoder();
  const widths = (rows[0] ?? [])
    .map((_, index) => `<col min="${index + 1}" max="${index + 1}" width="${index === 0 ? 26 : 18}" customWidth="1"/>`)
    .join('');

  const body = rows
    .map((row, rowIndex) => {
      const cells = row
        .map((value, colIndex) => {
          const ref = `${columnName(colIndex)}${rowIndex + 1}`;
          const style = rowIndex === 0 ? ' s="1"' : '';
          const numeric = rowIndex > 0 && value !== '' && /^-?\d+(\.\d+)?$/.test(value);
          return numeric
            ? `<c r="${ref}"${style}><v>${value}</v></c>`
            : `<c r="${ref}"${style} t="inlineStr"><is><t xml:space="preserve">${escapeXml(value)}</t></is></c>`;
        })
        .join('');
      return `<row r="${rowIndex + 1}">${cells}</row>`;
    })
    .join('');

  const sheet = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>
<cols>${widths}</cols>
<sheetData>${body}</sheetData>
</worksheet>`;

  return zip([
    { name: '[Content_Types].xml', bytes: encoder.encode(CONTENT_TYPES) },
    { name: '_rels/.rels', bytes: encoder.encode(ROOT_RELS) },
    { name: 'xl/workbook.xml', bytes: encoder.encode(WORKBOOK) },
    { name: 'xl/_rels/workbook.xml.rels', bytes: encoder.encode(WORKBOOK_RELS) },
    { name: 'xl/styles.xml', bytes: encoder.encode(STYLES) },
    { name: 'xl/worksheets/sheet1.xml', bytes: encoder.encode(sheet) },
  ]);
}

export function buildCsv(rows: string[][]): string {
  return rows
    .map((row) =>
      row
        .map((value) => (/[",\n]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value))
        .join(','),
    )
    .join('\r\n');
}
